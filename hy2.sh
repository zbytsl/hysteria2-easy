#!/usr/bin/env bash
# Hysteria 2 Easy Installer
# Copyright (c) 2026
# Supported: Debian 12+, Ubuntu 22.04+, systemd-based Linux
set -Eeuo pipefail
IFS=$'\n\t'

VERSION="1.0.0"
HY_DIR="/etc/hysteria"
HY_CONF="${HY_DIR}/config.yaml"
HY_CERT="${HY_DIR}/server.crt"
HY_KEY="${HY_DIR}/server.key"
HY_STATE="${HY_DIR}/hy2.env"
HY_SERVICE="hysteria-server.service"
HY_BIN="/usr/local/bin/hysteria"
SHORTCUT="/usr/local/bin/hy2"
OFFICIAL_INSTALLER="https://get.hy2.sh/"
DEFAULT_HOP="20000-50000"
DEFAULT_MASQ="https://news.ycombinator.com/"
DEFAULT_SNI="www.bing.com"

C_RESET=""; C_RED=""; C_GREEN=""; C_YELLOW=""; C_CYAN=""
if [[ -t 1 ]]; then
  C_RESET=$'\033[0m'; C_RED=$'\033[31m'; C_GREEN=$'\033[32m'
  C_YELLOW=$'\033[33m'; C_CYAN=$'\033[36m'
fi

info() { printf '%s[信息]%s %s\n' "$C_GREEN" "$C_RESET" "$*"; }
warn() { printf '%s[警告]%s %s\n' "$C_YELLOW" "$C_RESET" "$*" >&2; }
error() { printf '%s[错误]%s %s\n' "$C_RED" "$C_RESET" "$*" >&2; }
die() { error "$*"; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

require_root() { [[ ${EUID} -eq 0 ]] || die "请使用 root 运行：sudo -i"; }
require_systemd() {
  have systemctl && [[ -d /run/systemd/system ]] || die "当前系统未运行 systemd"
}
confirm() {
  local answer
  [[ ${HY2_YES:-0} == 1 ]] && return 0
  read -r -p "$1 [y/N]: " answer || return 1
  [[ "$answer" =~ ^([Yy]|[Yy][Ee][Ss])$ ]]
}
ask() {
  local var="$1" prompt="$2" default="${3-}" value="" env_name="HY2_${1}"
  if [[ -n ${!env_name:-} ]]; then printf -v "$var" '%s' "${!env_name}"; return; fi
  if [[ ${HY2_YES:-0} == 1 ]]; then printf -v "$var" '%s' "$default"; return; fi
  [[ -n "$default" ]] && prompt+=" [默认: ${default}]"
  read -r -p "${prompt}: " value || die "无法读取输入"
  [[ "$value" == "-" ]] && value=""
  printf -v "$var" '%s' "${value:-$default}"
}
valid_domain() {
  [[ "$1" =~ ^([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$ ]]
}
valid_password() { [[ "$1" =~ ^[A-Za-z0-9._~-]{8,64}$ ]]; }
valid_url() { local re='^https?://[A-Za-z0-9][A-Za-z0-9._~:/?&=%@+,-]*$'; [[ $1 =~ $re ]]; }

HOP_START="" HOP_END=""
parse_hop() {
  local value="${1//:/-}" a b
  if [[ "$value" =~ ^([0-9]{1,5})-([0-9]{1,5})$ ]]; then
    a="${BASH_REMATCH[1]}"; b="${BASH_REMATCH[2]}"
  elif [[ "$value" =~ ^[0-9]{1,5}$ ]]; then
    a="$value"; b="$value"
  else return 1; fi
  a=$((10#$a)); b=$((10#$b))
  (( a >= 1 && b <= 65535 && a <= b )) || return 1
  HOP_START="$a"; HOP_END="$b"
}
load_state() {
  [[ -f "$HY_STATE" ]] || return 0
  # State is generated by this script and restricted to root.
  [[ $(stat -c '%a' "$HY_STATE" 2>/dev/null || echo 777) == 600 ]] ||
    die "状态文件权限异常：${HY_STATE}（应为 600），请检查文件安全性"
  # shellcheck disable=SC1090
  source "$HY_STATE"
  [[ -n ${HOP:-} ]] && parse_hop "$HOP" || true
}
save_state() {
  umask 077
  {
    printf 'DOMAIN=%q\n' "$DOMAIN"
    printf 'SERVER_ADDR=%q\n' "$SERVER_ADDR"
    printf 'SNI=%q\n' "$SNI"
    printf 'HOP=%q\n' "$HOP"
    printf 'PASSWORD=%q\n' "$PASSWORD"
    printf 'MASQ_URL=%q\n' "$MASQ_URL"
    printf 'FW_TYPE=%q\n' "$FW_TYPE"
  } > "${HY_STATE}.tmp"
  chmod 600 "${HY_STATE}.tmp"
  mv -f "${HY_STATE}.tmp" "$HY_STATE"
}
detect_ip() {
  local family="$1" result=""
  result=$(curl "-${family}" -fsS --connect-timeout 4 --max-time 8 https://api.ipify.org 2>/dev/null || true)
  if [[ "$family" == 4 ]]; then
    [[ "$result" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] && printf '%s' "$result"
  else
    [[ "$result" == *:* ]] && printf '%s' "$result"
  fi
}
install_dependencies() {
  local packages=()
  have curl || packages+=(curl)
  have openssl || packages+=(openssl)
  have ss || packages+=(iproute2)
  if ! have nft && ! have iptables; then packages+=(nftables); fi
  if ((${#packages[@]})); then
    if have apt-get; then
      export DEBIAN_FRONTEND=noninteractive
      apt-get update
      apt-get install -y "${packages[@]}" ca-certificates
    elif have dnf; then dnf install -y "${packages[@]}" ca-certificates
    elif have yum; then yum install -y "${packages[@]}" ca-certificates
    else die "无法识别包管理器，请手动安装：${packages[*]}"; fi
  fi
}
check_port_conflicts() {
  local port
  while read -r port; do
    [[ "$port" =~ ^[0-9]+$ ]] || continue
    if (( port >= HOP_START && port <= HOP_END )); then
      die "UDP 端口 ${port} 已被监听。请更换端口范围后重试。"
    fi
  done < <(ss -H -lunp 2>/dev/null | grep -v '"hysteria"' | awk '{n=split($5,a,":"); print a[n]}')
}
get_server_address() {
  ask DOMAIN "服务器域名（没有域名请输入 -，使用公网 IP）" "${DOMAIN:-}"
  if [[ -n "$DOMAIN" ]]; then
    valid_domain "$DOMAIN" || die "域名格式无效"
    SERVER_ADDR="$DOMAIN"; SNI="$DOMAIN"
    local ips
    ips=$(getent ahosts "$DOMAIN" 2>/dev/null | awk '{print $1}' | sort -u || true)
    if [[ -z "$ips" ]]; then
      warn "域名暂时无法解析。请确认 DNS A/AAAA 记录指向本机公网 IP。"
      confirm "仍然继续？" || die "DNS 检查未通过"
    else
      local ip4 ip6
      ip4=$(detect_ip 4 || true); ip6=$(detect_ip 6 || true)
      if { [[ -n "$ip4" ]] && ! grep -qxF "$ip4" <<<"$ips"; } &&
         { [[ -z "$ip6" ]] || ! grep -qxF "$ip6" <<<"$ips"; }; then
        warn "域名解析结果与检测到的本机公网 IP 不一致：${ips//$'\n'/ }"
        warn "若使用 CDN/代理或特殊 NAT，请确认 UDP 流量确实能到达本机。"
        confirm "仍然继续？" || die "DNS 地址不匹配"
      fi
    fi
  else
    local ip4 ip6
    ip4=$(detect_ip 4 || true); ip6=$(detect_ip 6 || true)
    SERVER_ADDR="${ip4:-$ip6}"
    [[ -n "$SERVER_ADDR" ]] || die "无法获取服务器公网 IP"
    ask SNI "证书 SNI 域名（例如 www.bing.com）" "${SNI:-$DEFAULT_SNI}"
    valid_domain "$SNI" || die "SNI 格式无效"
  fi
}
ask_settings() {
  ask HOP "UDP 端口或端口范围（例如 443 或 20000-50000）" "${HOP:-$DEFAULT_HOP}"
  parse_hop "$HOP" || die "端口范围无效，范围必须为 1-65535 且起始端口不大于结束端口"
  check_port_conflicts
  if (( HOP_START < 1024 && HOP_END > HOP_START )); then
    warn "端口范围包含 1024 以下的端口，可能影响系统服务。"
    confirm "仍然继续？" || die "已取消"
  fi
  ask PASSWORD "连接密码（留空自动生成，至少 8 位）" ""
  [[ -n "$PASSWORD" ]] || PASSWORD=$(openssl rand -hex 16)
  valid_password "$PASSWORD" || die "密码格式无效：仅允许字母、数字、点、下划线、波浪线和连字符，长度 8-64"
  ask MASQ_URL "伪装站点 URL" "${MASQ_URL:-$DEFAULT_MASQ}"
  valid_url "$MASQ_URL" || die "伪装 URL 格式无效"
  if (( HOP_START == HOP_END )); then HOP="$HOP_START"; else HOP="${HOP_START}-${HOP_END}"; fi
}
generate_certificate() {
  local name="$1" san cfg
  if [[ "$name" == *:* || "$name" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]]; then san="IP:${name}"; else san="DNS:${name}"; fi
  install -d -m 750 "$HY_DIR"
  cfg=$(mktemp)
  cat > "$cfg" <<EOF
[req]
distinguished_name=dn
x509_extensions=v3
prompt=no
[dn]
CN=${name}
[v3]
subjectAltName=${san}
basicConstraints=CA:FALSE
keyUsage=digitalSignature
extendedKeyUsage=serverAuth
EOF
  openssl req -x509 -nodes -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 \
    -keyout "$HY_KEY" -out "$HY_CERT" -days 3650 -config "$cfg" >/dev/null 2>&1
  local rc=$?
  rm -f "$cfg"
  (( rc == 0 )) || return "$rc"
  chmod 644 "$HY_CERT"; chmod 600 "$HY_KEY"
}
fingerprint() {
  openssl x509 -in "$HY_CERT" -noout -fingerprint -sha256 | sed 's/^[^=]*=//'
}
configure_permissions() {
  local service_user group
  service_user=$(systemctl show -p User "$HY_SERVICE" 2>/dev/null | cut -d= -f2)
  service_user="${service_user:-hysteria}"
  if id "$service_user" >/dev/null 2>&1; then
    group=$(id -gn "$service_user")
    chown "$service_user:$group" "$HY_KEY"
    chown "root:$group" "$HY_CONF"
    chmod 600 "$HY_KEY"; chmod 640 "$HY_CONF"
  else
    chmod 600 "$HY_KEY"; chmod 600 "$HY_CONF"
  fi
  chmod 644 "$HY_CERT"
}
write_config() {
  if [[ -f "$HY_CONF" && ! -f "$HY_STATE" ]]; then
    cp -a "$HY_CONF" "${HY_CONF}.bak.$(date +%Y%m%d%H%M%S)"
    warn "发现已有配置，已备份后再覆盖。"
  fi
  local listen=":${HOP_START}"
  (( HOP_START == HOP_END )) || listen=":${HOP_START}-${HOP_END}"
  cat > "$HY_CONF" <<EOF
listen: "${listen}"

tls:
  cert: ${HY_CERT}
  key: ${HY_KEY}

auth:
  type: password
  password: "${PASSWORD}"

masquerade:
  type: proxy
  proxy:
    url: "${MASQ_URL}"
    rewriteHost: true
EOF
}
detect_firewall() {
  if have ufw && ufw status 2>/dev/null | grep -q '^Status: active'; then echo ufw
  elif have firewall-cmd && firewall-cmd --state >/dev/null 2>&1; then echo firewalld
  else echo none; fi
}
firewall_open() {
  local fw="$1" spec
  case "$fw" in
    ufw)
      spec="${HOP_START}:${HOP_END}/udp"
      (( HOP_START == HOP_END )) && spec="${HOP_START}/udp"
      ufw allow "$spec" || die "UFW 放行失败"
      ;;
    firewalld)
      spec="${HOP_START}-${HOP_END}/udp"
      (( HOP_START == HOP_END )) && spec="${HOP_START}/udp"
      firewall-cmd --permanent --add-port="$spec" || die "firewalld 放行失败"
      firewall-cmd --reload || die "firewalld reload 失败"
      ;;
    none) warn "未检测到正在运行的 UFW/firewalld；请在云厂商安全组放行 UDP ${HOP_START}-${HOP_END}。" ;;
  esac
}
install_core() {
  local tmp
  tmp=$(mktemp)
  curl -fsSL --retry 3 --connect-timeout 10 "$OFFICIAL_INSTALLER" -o "$tmp" ||
    { rm -f "$tmp"; die "无法下载 Hysteria 官方安装脚本"; }
  head -n1 "$tmp" | grep -q '^#!' || { rm -f "$tmp"; die "官方安装脚本格式异常"; }
  bash "$tmp"
  local rc=$?
  rm -f "$tmp"
  return "$rc"
}
configure_port_hopping_capability() {
  # Hysteria's built-in Linux port hopping installs NAT redirect rules.
  # Grant only the network-administration capability to the service.
  install -d -m 755 "/etc/systemd/system/${HY_SERVICE}.d"
  cat > "/etc/systemd/system/${HY_SERVICE}.d/10-port-hopping.conf" <<'EOF'
[Service]
AmbientCapabilities=CAP_NET_ADMIN
CapabilityBoundingSet=CAP_NET_ADMIN CAP_NET_BIND_SERVICE
EOF
  systemctl daemon-reload
}
restart_service() {
  systemctl enable "$HY_SERVICE" >/dev/null
  systemctl restart "$HY_SERVICE"
  sleep 2
  systemctl is-active --quiet "$HY_SERVICE" || {
    journalctl -u "$HY_SERVICE" -n 40 --no-pager || true
    die "Hysteria 服务启动失败"
  }
  info "Hysteria 服务运行正常并已设置开机自启"
}
show_info() {
  [[ -f "$HY_STATE" ]] || die "没有找到部署配置"
  load_state
  local fp host uri_name uri_port link
  fp=$(fingerprint)
  host="$SERVER_ADDR"
  [[ "$host" == *:* ]] && host="[${host}]"
  uri_name="Hysteria2-${SERVER_ADDR}"
  uri_port="$HOP_START"
  if (( HOP_START != HOP_END )); then uri_port="${HOP_START}-${HOP_END}"; fi
  # Hysteria URI encodes port hopping in the authority's port field, not mport=.
  link="hysteria2://${PASSWORD}@${host}:${uri_port}/?sni=${SNI}&insecure=1&pinSHA256=${fp//:/}"
  link+="#${uri_name}"
  printf '\n%s========== Hysteria 2 节点信息 ==========%s\n' "$C_CYAN" "$C_RESET"
  printf '服务状态：%s\n服务器地址：%s\nUDP 端口：%s\n密码：%s\nSNI：%s\n证书 SHA-256：%s\n' \
    "$(systemctl is-active "$HY_SERVICE" 2>/dev/null || true)" "$SERVER_ADDR" "$HOP" "$PASSWORD" "$SNI" "$fp"
  printf '\n分享链接：\n%s\n' "$link"
  printf '\n官方客户端配置：\n'
  local client_server="$SERVER_ADDR:$HOP_START"
  if (( HOP_START != HOP_END )); then client_server="$SERVER_ADDR:$HOP_START-$HOP_END"; fi
  cat <<EOF
server: "${client_server}"
auth: "${PASSWORD}"
tls:
  sni: "${SNI}"
  insecure: true
  pinSHA256: "${fp}"
EOF
  if (( HOP_START != HOP_END )); then
    printf 'transport:\n  udp:\n    hopInterval: 30s\n'
  fi
  local pubkey_pin
  pubkey_pin=$(openssl x509 -in "$HY_CERT" -pubkey -noout | openssl pkey -pubin -outform DER | openssl dgst -sha256 -binary | openssl base64 -A)
  printf '\nsing-box 1.13+ JSON 配置：\n'
  if (( HOP_START != HOP_END )); then
    cat <<EOF
{
  "type": "hysteria2",
  "tag": "hy2-out",
  "server": "${SERVER_ADDR}",
  "server_ports": ["${HOP_START}:${HOP_END}"],
  "hop_interval": "30s",
  "password": "${PASSWORD}",
  "tls": {
    "enabled": true,
    "server_name": "${SNI}",
    "insecure": true,
    "certificate_public_key_sha256": ["${pubkey_pin}"]
  }
}
EOF
  else
    cat <<EOF
{
  "type": "hysteria2",
  "tag": "hy2-out",
  "server": "${SERVER_ADDR}",
  "server_port": ${HOP_START},
  "password": "${PASSWORD}",
  "tls": {
    "enabled": true,
    "server_name": "${SNI}",
    "insecure": true,
    "certificate_public_key_sha256": ["${pubkey_pin}"]
  }
}
EOF
  fi
  printf '\nClash Meta / mihomo 配置：\n'
  cat <<EOF
proxies:
  - name: "${uri_name}"
    type: hysteria2
    server: "${SERVER_ADDR}"
    port: ${HOP_START}
EOF
  if (( HOP_START != HOP_END )); then
    printf '    ports: "%s-%s"\n    hop-interval: 30\n' "$HOP_START" "$HOP_END"
  fi
  cat <<EOF
    password: "${PASSWORD}"
    sni: "${SNI}"
    skip-cert-verify: true
    fingerprint: "${fp//:/}"
    alpn:
      - h3
EOF
  printf '\n注意：自签证书重新生成后，客户端必须同步更新指纹。\n'
  printf '另外，请在云厂商安全组放行 UDP %s。\n' "$HOP"
}
do_install() {
  require_root; require_systemd
  install_dependencies
  info "开始安装 Hysteria 2 官方内核..."
  install_core || die "官方安装器执行失败"
  [[ -x "$HY_BIN" ]] || die "安装完成后未找到 ${HY_BIN}"
  DOMAIN=""; SERVER_ADDR=""; SNI=""; HOP=""; PASSWORD=""; MASQ_URL=""; FW_TYPE=""
  get_server_address
  ask_settings
  generate_certificate "$SNI" || die "证书生成失败"
  write_config
  configure_port_hopping_capability
  FW_TYPE=$(detect_firewall)
  firewall_open "$FW_TYPE"
  save_state
  configure_permissions
  restart_service
  show_info
  install -m 755 "$(readlink -f "$0")" "$SHORTCUT" 2>/dev/null || true
}
do_config() {
  require_root; require_systemd
  [[ -x "$HY_BIN" ]] || die "请先安装 Hysteria 2"
  load_state
  local old_cert="${SNI:-}"
  get_server_address
  ask_settings
  if [[ -f "$HY_CERT" && -f "$HY_KEY" && "$old_cert" == "$SNI" ]]; then
    info "沿用现有证书"
  else generate_certificate "$SNI" || die "证书生成失败"; fi
  write_config
  configure_port_hopping_capability
  FW_TYPE=$(detect_firewall)
  firewall_open "$FW_TYPE"
  save_state
  configure_permissions
  restart_service
  show_info
}
do_cert() {
  require_root; load_state
  [[ -n ${SNI:-} ]] || die "没有部署状态"
  warn "重新生成证书会改变指纹，所有客户端都需要更新。"
  confirm "确定重新生成？" || return 0
  generate_certificate "$SNI" || die "证书生成失败"
  configure_permissions
  restart_service
  show_info
}
do_update() {
  require_root; require_systemd
  [[ -x "$HY_BIN" ]] || die "Hysteria 尚未安装"
  local old
  old=$("$HY_BIN" version 2>/dev/null | head -n1 || true)
  install_core || die "更新失败"
  restart_service
  info "更新完成：${old} -> $("$HY_BIN" version 2>/dev/null | head -n1)"
}
do_uninstall() {
  require_root; require_systemd
  load_state
  warn "将停止并卸载 Hysteria 2。配置目录默认保留，避免误删证书和密码。"
  confirm "确认卸载？" || return 0
  systemctl disable --now "$HY_SERVICE" >/dev/null 2>&1 || true
  local tmp
  tmp=$(mktemp)
  if curl -fsSL --retry 2 "$OFFICIAL_INSTALLER" -o "$tmp"; then
    bash "$tmp" --remove || warn "官方卸载器执行失败，将继续清理服务文件"
  fi
  rm -f "$tmp"
  rm -f "/etc/systemd/system/${HY_SERVICE}.d/10-port-hopping.conf"
  rmdir "/etc/systemd/system/${HY_SERVICE}.d" 2>/dev/null || true
  systemctl daemon-reload
  rm -f "$SHORTCUT"
  if confirm "是否同时删除 ${HY_DIR}（含密码、证书和配置）？"; then
    rm -rf -- "$HY_DIR"
  else
    warn "已保留配置目录：${HY_DIR}"
  fi
  info "卸载流程完成"
}
service_action() {
  require_root; require_systemd
  case "$1" in
    start) systemctl start "$HY_SERVICE" ;;
    stop) systemctl stop "$HY_SERVICE" ;;
    restart) systemctl restart "$HY_SERVICE" ;;
    status) systemctl status "$HY_SERVICE" --no-pager; return ;;
    log) journalctl -u "$HY_SERVICE" -n 80 --no-pager; return ;;
  esac
  info "已执行：$1"
}
menu() {
  local choice
  while true; do
    printf '\n%s===== Hysteria 2 Easy Installer v%s =====%s\n' "$C_CYAN" "$VERSION" "$C_RESET"
    printf '1. 安装 Hysteria 2\n2. 重新配置\n3. 查看节点信息\n4. 服务管理\n5. 重新生成证书\n6. 更新内核\n7. 卸载\n0. 退出\n'
    read -r -p "请选择 [0-7]: " choice || exit 0
    case "$choice" in
      1) do_install ;;
      2) do_config ;;
      3) show_info ;;
      4)
        printf '1.启动 2.停止 3.重启 4.状态 5.日志\n'
        read -r -p "请选择: " choice
        case "$choice" in 1) service_action start;; 2) service_action stop;; 3) service_action restart;; 4) service_action status;; 5) service_action log;; esac
        ;;
      5) do_cert ;;
      6) do_update ;;
      7) do_uninstall ;;
      0) exit 0 ;;
      *) warn "无效选项" ;;
    esac
  done
}
usage() {
  cat <<EOF
Hysteria 2 Easy Installer v${VERSION}
用法：hy2.sh [menu|install|config|info|cert|update|uninstall|start|stop|restart|status|log]
非交互变量：HY2_YES=1 HY2_DOMAIN HY2_SNI HY2_HOP HY2_PASSWORD HY2_MASQ_URL
EOF
}
main() {
  local cmd="${1:-menu}"
  case "$cmd" in
    -h|--help|help) usage ;;
    menu) require_root; menu ;;
    install) do_install ;;
    config) do_config ;;
    info) show_info ;;
    cert) do_cert ;;
    update) do_update ;;
    uninstall) do_uninstall ;;
    start|stop|restart|status|log) service_action "$cmd" ;;
    *) usage; exit 2 ;;
  esac
}
main "$@"
